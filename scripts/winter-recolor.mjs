// Winter recolor generator for src/styles.css.
// Every season-independent rule that hard-codes a warm (orange/amber/brown) color gets a winter
// override scoped to `.app-shell-dark.season-winter`, written between the markers below.
// Run after adding or changing such a rule:  node scripts/winter-recolor.mjs
// tests/season-winter.test.mjs fails while any warm rule is missing its winter override.
import {readFileSync,writeFileSync} from 'node:fs';
import {fileURLToPath} from 'node:url';

export const START='/* Part 2 — generated winter recolor of season-independent warm colors */';
export const END='/* End of generated winter recolor */';
const COLOR=/#(?:[0-9a-fA-F]{6}|[0-9a-fA-F]{3})\b|rgba?\([^)]*\)/g;
const SEASON_SCOPED=/season-(autumn|summer|spring|winter)/;
// Activity identity colors keep distinct winter hues instead of all turning ice blue.
const IDENTITY=[[/combat/,'berry'],[/tabata-card\.work/,'berry'],[/crossfit/,'frost'],[/moto/,'steel'],[/outdoor-run|\.run\b/,'aqua']];

function parse(c){
 if(c[0]==='#'){let h=c.slice(1);if(h.length===3)h=[...h].map(x=>x+x).join('');return [0,2,4].map(i=>parseInt(h.slice(i,i+2),16)).concat(1);}
 const p=c.slice(c.indexOf('(')+1).split(/[ ,/()]+/).filter(Boolean).map(Number);return [p[0],p[1],p[2],p[3]===undefined?1:p[3]];
}
function toHsl(r,g,b){r/=255;g/=255;b/=255;const mx=Math.max(r,g,b),mn=Math.min(r,g,b),l=(mx+mn)/2,d=mx-mn;if(!d)return [0,0,l];const s=l>.5?d/(2-mx-mn):d/(mx+mn);let h=mx===r?((g-b)/d)%6:mx===g?(b-r)/d+2:(r-g)/d+4;h*=60;if(h<0)h+=360;return [h,s,l];}
function fromHsl(h,s,l){const k=n=>(n+h/30)%12,a=s*Math.min(l,1-l),f=n=>l-a*Math.max(-1,Math.min(k(n)-3,9-k(n),1));return [f(0)*255,f(8)*255,f(4)*255];}
export function isWarm(c){
 let r,g,b,a;try{[r,g,b,a]=parse(c);}catch{return false;}
 if(!(a>=0.06))return false;
 const [h,s,l]=toHsl(r,g,b),d=Math.max(r,g,b)-Math.min(r,g,b);
 if(l<0.25)return h>=8&&h<=58&&d>=5;          // brown-black panels
 if(d<15)return false;
 return h>=8&&h<=58&&s>0.3&&l<0.92;
}
function fmt([r,g,b],a,orig){
 [r,g,b]=[r,g,b].map(x=>Math.max(0,Math.min(255,Math.round(x))));
 if(orig[0]==='#'&&a===1)return '#'+[r,g,b].map(x=>x.toString(16).padStart(2,'0')).join('');
 return `rgba(${r},${g},${b},${+a.toFixed(3)})`;
}
export function winterColor(c,selector=''){
 const [r,g,b,a]=parse(c);let [,s,l]=toHsl(r,g,b);
 const kind=IDENTITY.find(([re])=>re.test(selector))?.[1];
 if(kind==='berry')return fmt(fromHsl(346,Math.min(1,s)*0.82,l),a,c);
 if(kind==='aqua')return fmt(fromHsl(168,Math.min(1,s)*0.82,l),a,c);
 if(kind==='steel')return fmt(fromHsl(210,0.42,l),a,c);
 if(kind==='frost')return fmt(fromHsl(205,0.9,Math.max(l,0.86)),a,c);
 if(l<0.32)return fmt(fromHsl(214,Math.min(s,0.55),l),a,c);   // brown panels -> deep navy
 if(l>0.8)return fmt(fromHsl(204,Math.min(s,0.95),l),a,c);     // pale peach -> frost
 return fmt(fromHsl(203,Math.min(1,s*0.95),l),a,c);            // vivid orange/amber -> ice blue
}
function blocks(css,re){const out=[];for(const m of css.matchAll(re)){let depth=1,i=m.index+m[0].length;while(depth&&i<css.length){if(css[i]==='{')depth++;else if(css[i]==='}')depth--;i++;}out.push([m.index,i,m[0].slice(0,-1).trim()]);}return out;}
function source(css){const a=css.indexOf(START),b=css.indexOf(END);return a<0||b<0?css:css.slice(0,a)+css.slice(b+END.length);}
export function winterPrefix(part){part=part.trim();return part.startsWith('.app-shell-dark')?'.app-shell-dark.season-winter'+part.slice('.app-shell-dark'.length):'.app-shell-dark.season-winter '+part;}
// [{selector, parts, declarations, media}] for season-independent rules with warm colors
export function warmRules(fullCss){
 const css=source(fullCss),media=blocks(css,/@(?:media|supports)[^{]*\{/g),frames=blocks(css,/@keyframes[^{]*\{/g),out=[];
 for(const m of css.matchAll(/([^{}]+)\{([^{}]*)\}/g)){
  const pos=m.index+m[1].length;
  if(frames.some(([a,b])=>a<=pos&&pos<=b))continue;
  const selector=m[1].replace(/\/\*[\s\S]*?\*\//g,'').split(/\s+/).join(' ').trim();
  if(!selector||selector.startsWith('@')||SEASON_SCOPED.test(selector)||/^(:root|html|body|\*)\b/.test(selector))continue;
  const declarations=[];
  for(const d of m[2].split(/;(?![^()]*\))/)){
   const i=d.indexOf(':');if(i<0)continue;
   const value=d.slice(i+1);if(!(value.match(COLOR)||[]).some(isWarm))continue;
   declarations.push(`${d.slice(0,i).trim()}:${value.replace(COLOR,c=>isWarm(c)?winterColor(c,selector):c).split(/\s+/).join(' ').trim()}`);
  }
  if(!declarations.length)continue;
  out.push({selector,parts:selector.split(',').map(p=>p.trim()),declarations,media:media.filter(([a,b])=>a<=pos&&pos<=b).at(-1)?.[2]});
 }
 return out;
}
export function generate(fullCss){
 const rules=warmRules(fullCss).map(r=>{const block=r.parts.map(winterPrefix).join(',\n')+'{'+r.declarations.join(';')+'}';return r.media?`${r.media}{${block}}`:block;});
 return `${START}\n/* generated by scripts/winter-recolor.mjs: ${rules.length} rules */\n${rules.join('\n')}\n${END}\n`;
}
if(process.argv[1]===fileURLToPath(import.meta.url)){
 const file=new URL('../src/styles.css',import.meta.url),css=readFileSync(file,'utf8');
 const a=css.indexOf(START),b=css.indexOf(END);
 const next=a<0?css.trimEnd()+'\n\n'+generate(css):css.slice(0,a)+generate(css)+css.slice(b+END.length).replace(/^\n/,'');
 writeFileSync(file,next);console.log('winter recolor rules:',warmRules(css).length);
}
